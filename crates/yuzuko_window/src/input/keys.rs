//! UI Events `code` and `key` names for winit's keyboard enums.

use winit::keyboard::{Key, KeyCode, KeyLocation, NamedKey, PhysicalKey};

pub fn code_name(key: PhysicalKey) -> &'static str {
  match key {
    PhysicalKey::Code(code) => code_of(code),
    PhysicalKey::Unidentified(_) => "Unidentified",
  }
}

pub fn key_name(key: &Key) -> String {
  match key {
    Key::Character(text) => text.to_string(),
    Key::Named(named) => named_key(*named).to_string(),
    Key::Dead(_) => "Dead".to_string(),
    Key::Unidentified(_) => "Unidentified".to_string(),
  }
}

pub fn location_value(location: KeyLocation) -> u32 {
  match location {
    KeyLocation::Standard => 0,
    KeyLocation::Left => 1,
    KeyLocation::Right => 2,
    KeyLocation::Numpad => 3,
  }
}

